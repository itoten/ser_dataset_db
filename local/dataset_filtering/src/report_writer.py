"""Writes the outputs of one config to output/<config name>/.

summary.md   what the config does, counts per step, and per step the datasets it removed or left unverified
result.csv   one row per dataset in the DB: status, the step that removed it and why
filter.log   every verdict of every step for every dataset, with its reason (tab separated)
"""
import csv
from collections import Counter
from datetime import date
from pathlib import Path

from .dataset_filter import DatasetFilter, Outcome

FOLD_ABOVE = 20  # longer dataset lists are folded in summary.md


class ReportWriter:
    def __init__(self, output_dir):
        self.output_dir = Path(output_dir)

    def write(self, pipeline, results):
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.write_result(results)
        self.write_log(results)
        self.write_summary(pipeline, results)

    def write_result(self, results):
        fields = ["dataset_id", "name", "status", "removed_by", "reason", "unverified"]
        with open(self.output_dir / "result.csv", "w", encoding="utf-8", newline="") as f:
            w = csv.DictWriter(f, fieldnames=fields, lineterminator="\n")
            w.writeheader()
            for r in results:
                w.writerow({"dataset_id": r.dataset.id, "name": r.dataset.name, "status": r.status,
                            "removed_by": r.removed_by,
                            "reason": r.verdicts[-1][1].reason if r.removed_by else "",
                            "unverified": "; ".join(f"{n}: {v.reason}" for n, v in r.verdicts
                                                    if v.outcome is Outcome.UNVERIFIED)})

    def write_log(self, results):
        with open(self.output_dir / "filter.log", "w", encoding="utf-8") as f:
            f.write("dataset_id\tstep\tverdict\treason\n")
            for r in results:
                for name, v in r.verdicts:
                    f.write(f"{r.dataset.id}\t{name}\t{v.outcome.value}\t{v.reason}\n")

    def write_summary(self, pipeline, results):
        name = self.output_dir.name
        counts = Counter(r.status for r in results)
        lines = [f"# Dataset filtering: {name}", "",
                 f"Generated by run.py on {date.today()} from DB commit {pipeline.database.load_commit()}"
                 f" with config/{name}.yaml. Do not edit.", "",
                 "## 1. About this config", "", pipeline.config.get("description", "").strip(), "",
                 "## 2. Counts", "",
                 f"Kept {counts['kept']}, kept but unverified {counts['kept_unverified']}, removed {counts['removed']}.", "",
                 "| Step | Removed here | Left | Of those left, unverified here |", "|---|---|---|---|",
                 f"| (all datasets in the DB) | | {len(results)} | |"]
        left = len(results)
        for step in pipeline.steps:
            left -= sum(1 for r in results if r.removed_by == step.name)
            removed = sum(1 for r in results if r.removed_by == step.name)
            flagged = sum(1 for r in results if r.status != "removed" and step.name in r.unverified_by)
            lines.append(f"| {step.name} | {removed} | {left} | {flagged} |")

        lines += ["", "## 3. Steps"]
        for i, step in enumerate(pipeline.steps, 1):
            lines += self.format_step(f"3.{i}", step, results)

        kept = [r for r in results if r.status != "removed"]
        lines += ["", f"## 4. Kept datasets ({len(kept)})", ""]
        lines += self.format_datasets(kept, lambda r: r.status)
        (self.output_dir / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    def format_step(self, number, step, results):
        doc = (getattr(DatasetFilter, step.filter).__doc__ or "").strip()
        lines = ["", f"### {number} {step.name}", "", f"Filter `{step.filter}`: {doc}"]
        if step.note:
            lines += ["", step.note.strip()]
        for key, value in step.params.items():
            lines += [""] + self.format_param(key, value)
        removed = [r for r in results if r.removed_by == step.name]
        flagged = [r for r in results if r.status != "removed" and step.name in r.unverified_by]
        lines += ["", f"Removed here: {len(removed)}", ""]
        lines += self.format_datasets(removed, lambda r: r.verdicts[-1][1].reason)
        if flagged:
            lines += ["", f"Kept but unverified here: {len(flagged)}", ""]
            lines += self.format_datasets(flagged, lambda r: dict(r.verdicts)[step.name].reason)
        return lines

    @staticmethod
    def format_param(key, value):
        if isinstance(value, list) and value and isinstance(value[0], dict):
            fields = list(value[0])
            rows = [f"`{key}`:", "", "| " + " | ".join(fields) + " |", "|" + "---|" * len(fields)]
            rows += ["| " + " | ".join(str(e.get(k, "")).replace("|", "/") for k in fields) + " |" for e in value]
            return rows
        return [f"`{key}`: `{value}`"]

    @staticmethod
    def format_datasets(results, describe):
        if not results:
            return ["(none)"]
        rows = ["| dataset_id | name | detail |", "|---|---|---|"]
        rows += [f"| {r.dataset.id} | {r.dataset.name} | {describe(r).replace('|', '/')} |" for r in results]
        if len(results) > FOLD_ABOVE:
            return [f"<details><summary>{len(results)} datasets</summary>", ""] + rows + ["", "</details>"]
        return rows
